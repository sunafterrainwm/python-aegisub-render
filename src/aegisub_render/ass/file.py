"""AssFile (src/ass_file.cpp)."""

import bisect
import copy
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Self

from aegisub_render._crt import atoi, cdiv, wrap_int32
from aegisub_render.ass.entries import (
    AssAttachment,
    AssDialogue,
    AssInfo,
    AssStyle,
    ExtradataEntry,
    ProjectProperties,
)

if TYPE_CHECKING:  # .parser imports this module; the methods below import it at run time
    from aegisub_render.ass.parser import AssParser


@dataclass(slots=True)
class AssFile:
    info: list[AssInfo] = field(default_factory=list[AssInfo])
    styles: list[AssStyle] = field(default_factory=list[AssStyle])
    events: list[AssDialogue] = field(default_factory=list[AssDialogue])
    attachments: list[AssAttachment] = field(default_factory=list[AssAttachment])
    extradata: list[ExtradataEntry] = field(default_factory=list[ExtradataEntry])
    properties: ProjectProperties = field(default_factory=ProjectProperties)
    next_extradata_id: int = 1
    # Whether the file these were read from had the sections (not part of Aegisub's AssFile).
    had_project_garbage: bool = False
    had_extradata: bool = False
    # The ';' comment lines that opened its [Script Info] section ("; Script generated by ..."),
    # which Aegisub drops; the writer uses them for the header (see writer.header_lines).
    header_comments: list[str] = field(default_factory=list[str])

    def __len__(self) -> int:
        """Same as file.events.__len__()"""
        return self.events.__len__()

    def __iter__(self) -> Iterator[AssDialogue]:
        """Same as file.events.__iter__()"""
        return self.events.__iter__()

    # Reading and writing live in .parser and .writer, which import this module; these are the
    # convenient way in and out of an AssFile, so they are bound here with a runtime import.
    #
    # parser_cls is the AssParser subclass to parse with (None: AssParser). It decides which
    # classes the result is made of, including the AssFile itself (AssParser.make_file), so
    # `MyAssFile.from_text(text)` without one still returns a plain AssFile.
    @classmethod
    def from_text(cls, text: str, version: int = 1, parser_cls: type[AssParser] | None = None) -> AssFile:
        """Parse already-decoded subtitle text (version 0 parses it as SSA, like a .ssa file)."""
        from aegisub_render.ass.parser import AssParser, parse_ass_text

        return parse_ass_text(text, version, parser_cls or AssParser)

    @classmethod
    def from_bytes(cls, raw: bytes, version: int = 1, parser_cls: type[AssParser] | None = None) -> AssFile:
        """Parse a .ass file's bytes: UTF-8 (BOM optional) or UTF-16 with a BOM.

        Raises parser.UnsupportedEncodingError for anything else.
        """
        from aegisub_render.ass.parser import AssParser, parse_ass_bytes

        return parse_ass_bytes(raw, version, parser_cls or AssParser)

    @classmethod
    def from_path(cls, path: Path, parser_cls: type[AssParser] | None = None) -> AssFile:
        """Read a subtitle file; a .ssa suffix is parsed as SSA, like Aegisub."""
        from aegisub_render.ass.parser import AssParser, read_ass_file

        return read_ass_file(path, parser_cls or AssParser)

    def serialize(self, save_ui_state: bool = True, keep_brand: bool = False) -> bytes:
        """This file as Aegisub's Save writes it (UTF-8 BOM, CRLF). Calls clean_extradata."""
        from aegisub_render.ass.writer import serialize_ass

        return serialize_ass(self, save_ui_state, keep_brand)

    def export(self, save_ui_state: bool = True, keep_brand: bool = False) -> bytes:
        """This file as File -> Export writes it: no [Aegisub Project Garbage] / [Aegisub
        Extradata] unless the file it was read from had them (see writer.serialize_export).
        """
        from aegisub_render.ass.writer import serialize_export

        return serialize_export(self, save_ui_state, keep_brand)

    def copy(self) -> Self:
        """A separate file with the same contents; every event gets a new id.

        Aegisub's AssFile copy constructor: info, attachments and extradata are copied, styles
        and events cloned (AssDialogue's copy constructor hands out a new Id). Deliberately
        unlike Aegisub: properties and header_comments come along as well -- its copy ctor leaves
        Properties default-initialised, which is of no use to a caller who wanted this file.
        """
        other = copy.deepcopy(self)
        other.events = [line.copy() for line in self.events]
        return other

    def line_count(self) -> int:
        return len(self.info) + len(self.styles) + len(self.events)

    def get_script_info(self, key: str) -> str:
        lk = key.lower()
        for info in self.info:
            if info.key.lower() == lk:
                return info.value
        return ""

    def get_script_info_int(self, key: str) -> int:
        return atoi(self.get_script_info(key))

    def get_resolution(self) -> tuple[int, int]:
        sw = self.get_script_info_int("PlayResX")
        sh = self.get_script_info_int("PlayResY")
        # Gabest logic: default is 384x288, assume 1280x1024 if either height or
        # width are that, otherwise assume 4:3 if only height or width are set.
        if sw == 0 and sh == 0:
            sw, sh = 384, 288
        elif sw == 0:
            sw = 1280 if sh == 1024 else wrap_int32(cdiv(sh * 4, 3))
        elif sh == 0:
            sh = 1024 if sw == 1280 else wrap_int32(cdiv(sw * 3, 4))
        return sw, sh

    def get_styles(self) -> list[str]:
        """AssFile::GetStyles: the names of the styles, in file order."""
        return [style.name for style in self.styles]

    def get_style(self, name: str) -> AssStyle | None:
        """AssFile::GetStyle: the first style with that name, compared case-insensitively."""
        lower = name.lower()
        return next((style for style in self.styles if style.name.lower() == lower), None)

    def add_extradata(self, key: str, value: str) -> int:
        for data in self.extradata:
            if data.key == key and data.value == value:
                return data.id
        self.extradata.append(ExtradataEntry(self.next_extradata_id, key, value))
        self.next_extradata_id = (self.next_extradata_id + 1) & 0xFFFFFFFF
        return self.extradata[-1].id

    def _enumerate_extradata(self, id_list: list[int]) -> list[ExtradataEntry]:
        """enumerate_extradata: lower_bound over the (id-sorted) list, without an equality check."""
        result: list[ExtradataEntry] = []
        ids = [e.id for e in self.extradata]
        begin = 0
        for wanted in id_list:
            idx = bisect.bisect_left(ids, wanted, lo=begin)
            if idx != len(ids):
                result.append(self.extradata[idx])
                begin = idx
        return result

    def get_extradata(self, id_list: list[int]) -> list[ExtradataEntry]:
        return self._enumerate_extradata(id_list)

    def clean_extradata(self) -> None:
        if not self.extradata:
            return
        ids_used: set[int] = set()
        for line in self.events:
            if not line.extradata_ids:
                continue
            keys_used: dict[str, int] = {}
            for e in self._enumerate_extradata(line.extradata_ids):
                keys_used[e.key] = e.id
            ids_used.update(keys_used.values())
            if len(keys_used) != len(line.extradata_ids):
                line.extradata_ids = sorted(keys_used.values())
        if len(ids_used) != len(self.extradata):
            self.extradata = [e for e in self.extradata if e.id in ids_used]
