TEMPLATE_ASS = MINIMAL_ASS.replace(
    "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n",
    "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    "Comment: 0,0:00:00.00,0:00:00.00,Default,,0,0,0,template syl,{\\pos($scenter,$smiddle)\\an5}\n",
)


ROOT = Path(__file__).resolve().parent.parent


def cli(*args: str, timeout: float = 120) -> subprocess.CompletedProcess[str]:
    if args and args[0] in ("render", "list") and is_wsl() and (fonts := wsl_test_fonts()) is not None:
        args = (args[0], "--font-dir", str(fonts), *args[1:])
    return subprocess.run(
        [sys.executable, str(ROOT / "aegisub-render.py"), *args],
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=timeout,
        check=False,
    )


def write(path: Path, text: str) -> Path:
    path.write_text(text, encoding="utf-8-sig")
    return path


def script(tmp_path: Path, body: str) -> Path:
    p = tmp_path / "s.lua"
    p.write_text(
        textwrap.dedent(
            """
            script_name = "s"
            aegisub.register_macro("m", "", function(subs)
            %s
            end)
            """
        )
        % body,
        encoding="utf-8",
    )
    return p


def test_keep_brand(tmp_path: Path, settings: Settings) -> None:
    header = "[Script Info]\n; Script generated by Aegisub 3.4.2\n; https://aegisub.org/\n"
    src = write(tmp_path / "in.ass", TEMPLATE_ASS.replace("[Script Info]\n", header, 1))
    for flags, first in (
        ((), "; Script generated by Aegisub 3.4.2 with aegisub-render "),
        (("--no-keep-brand",), "; Script generated by Aegisub 3.4.2 with aegisub-render "),
        (("--keep-brand",), "; Script generated by Aegisub 3.4.2\n; https://aegisub.org/\nTitle"),
    ):
        r = cli("render", str(src), "-o", "-", *flags)
        assert r.returncode == 0, r.stderr
        assert r.stdout.startswith("﻿[Script Info]\n" + first), r.stdout[:120]


