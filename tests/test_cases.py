"""Tests over the generated cases in tests/cases (see scripts/gen_cases.py).

* tests/aegisub/<case>.ass is the case exported from Aegisub 3.5.1: File > Export Subtitles with the
  "Karaoke template" filter. Running that export filter must reproduce it byte for byte, except for
  the "; Script generated by" line, which in ours also names aegisub-render.
* The macro (Apply karaoke template, then File > Save) must give the same file plus the
  [Aegisub Project Garbage] section, which Save writes and Export leaves out.
* tests/snapshots/<case>.ass is the macro output as recorded, which also covers that section.
  Re-record with:  AEGISUB_RENDER_UPDATE_SNAPSHOTS=1 uv run pytest tests/test_cases.py (on Windows)

Both the references and the snapshots are Windows output: text_extents is measured with GDI. Elsewhere
it is measured like Aegisub on Linux (fontconfig + HarfBuzz), which gives slightly different sizes, so
there the files must agree line for line except for numbers, each within MEASUREMENT_TOLERANCE.
"""

import io
import os
import re
from pathlib import Path

import pytest

from aegisub_render.ass.writer import AEGISUB_VERSION_STRING
from aegisub_render.host import _font
from aegisub_render.output import Output
from aegisub_render.runner import RenderOptions, output_data, read_input_ass, script_render
from aegisub_render.settings import Settings
from aegisub_render.version import __version__
from aegisub_render.video.context import update_relative_paths
from aegisub_render.worker import execute

HERE = Path(__file__).parent
CASES = sorted((HERE / "cases").glob("*.ass"))
IDS = [c.stem for c in CASES]
SNAPSHOTS = HERE / "snapshots"
AEGISUB = HERE / "aegisub"
UPDATE = os.environ.get("AEGISUB_RENDER_UPDATE_SNAPSHOTS") == "1"
EXPORT_FILTER = "Karaoke template"
AEGISUB_HEADER = f"; Script generated by Aegisub {AEGISUB_VERSION_STRING}"
OUR_HEADER = f"{AEGISUB_HEADER} with aegisub-render {__version__}"
# the references and snapshots were measured with GDI; the fcft build of _font measures differently
GDI = _font.backend() == "gdi"
# outside Windows: how far a number may be from Windows' (relative, absolute), measured: 4.2% and 32
MEASUREMENT_TOLERANCE = (0.05, 1.0)
_NUMBER = re.compile(r"-?\d+(?:\.\d+)?")


def assert_same_output(ours: list[str], windows: list[str], what: str) -> None:
    """Byte for byte with GDI; otherwise the same lines except for measurement-derived numbers."""
    if GDI or ours == windows:
        assert ours == windows, what
        return
    masked = [_NUMBER.sub("#", line) for line in ours]
    assert masked == [_NUMBER.sub("#", line) for line in windows], f"{what}: more than numbers differ"
    rel, absolute = MEASUREMENT_TOLERANCE
    for a, b in zip(ours, windows, strict=True):
        for x, y in zip(_NUMBER.findall(a), _NUMBER.findall(b), strict=True):
            fx, fy = float(x), float(y)
            assert abs(fx - fy) <= max(absolute, rel * abs(fy)), f"{what}: {x} vs {y} in {a!r}"


def render_case(path: Path, settings: Settings, filter: str | None = None) -> tuple[bytes, str]:
    stream = io.StringIO()
    out = Output(stream=stream, progress=False)
    options = RenderOptions(progress=False)
    ass = read_input_ass(path, settings.max_input_lines)
    sr = script_render(ass, path, settings, options, out, isolate=False, filter=filter)
    for w in sr.warnings:
        out.message(w)
    update_relative_paths(ass, sr.video, sr.paths)
    result = execute(sr.job, out)
    assert result.status == "ok", stream.getvalue() + result.message
    assert result.ass is not None
    data = output_data(result.ass, sr.is_filter, sr.save_ui_state, keep_brand=False)
    return data, stream.getvalue()


def lines(data: bytes) -> list[str]:
    """Lossless (the BOM stays on the first line), but compares with a readable diff."""
    return data.decode("utf-8").split("\r\n")


def as_aegisub(data: bytes) -> list[str]:
    out = lines(data)
    assert out[1] == OUR_HEADER
    out[1] = AEGISUB_HEADER
    return out


def without_project_garbage(data: bytes) -> bytes:
    """Drop the section that Save writes and Export does not, with the blank line before it."""
    out = data.split(b"\r\n")
    start = out.index(b"[Aegisub Project Garbage]")
    end = out.index(b"", start)
    return b"\r\n".join(out[: start - 1] + out[end:])


def reference(case: Path) -> list[str]:
    path = AEGISUB / case.name
    if not path.exists():
        pytest.fail(
            f"no Aegisub output for {case.name}: open it in Aegisub {AEGISUB_VERSION_STRING} and save "
            f"File > Export Subtitles with the {EXPORT_FILTER!r} filter as tests/aegisub/{case.name}"
        )
    return lines(path.read_bytes())


@pytest.mark.parametrize("case", CASES, ids=IDS)
def test_export_matches_aegisub(case: Path, settings: Settings) -> None:
    ours, log = render_case(case, settings, EXPORT_FILTER)
    assert "runtime error" not in log, log
    assert_same_output(as_aegisub(ours), reference(case), f"tests/aegisub/{case.name}")


@pytest.mark.parametrize("case", CASES, ids=IDS)
def test_macro(case: Path, settings: Settings) -> None:
    first, log = render_case(case, settings)
    second, _ = render_case(case, settings)
    assert first == second, "rendering is not deterministic"
    assert "runtime error" not in log, log

    snapshot = SNAPSHOTS / case.name
    if (UPDATE or not snapshot.exists()) and GDI:
        if not UPDATE:
            pytest.fail(f"no snapshot for {case.name}; record it with AEGISUB_RENDER_UPDATE_SNAPSHOTS=1")
        SNAPSHOTS.mkdir(exist_ok=True)
        snapshot.write_bytes(first)
    else:
        assert_same_output(lines(first), lines(snapshot.read_bytes()), f"tests/snapshots/{case.name}")

    assert_same_output(as_aegisub(without_project_garbage(first)), reference(case), f"tests/aegisub/{case.name}")


def test_unknown_variable_warnings_match_aegisub(tmp_path: Path, settings: Settings) -> None:
    """The original 02-line-preline used `$align`, which kara-templater does not define; Aegisub 3.5.0
    logged this exact text once per karaoke line and still produced output."""
    case = HERE / "cases" / "02-line-preline.ass"
    old = r"{\an$align\fad(150,150)\blur2}"
    new = r"{\an!line.styleref.align!\fad(150,150)\blur2}"
    src = tmp_path / case.name
    data = case.read_bytes()
    assert new.encode() in data
    src.write_bytes(data.replace(new.encode(), old.encode()))
    _, log = render_case(src, settings)
    warning = f"Unknown variable name: align\nIn karaoke template: {old}\n\n"
    assert log == warning * 3
