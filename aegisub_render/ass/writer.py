"""Writing .ass files exactly like AssSubtitleFormat::WriteFile/ExportFile on Windows (UTF-8 BOM, CRLF)."""

import re
from pathlib import Path

from aegisub_render._crt import format_f
from aegisub_render.ass.codec import inline_string_encode, uuencode
from aegisub_render.ass.entries import GROUP_HEADERS, AnyEntry, Group, ProjectProperties
from aegisub_render.ass.file import AssFile
from aegisub_render.textenc import to_bytes
from aegisub_render.version import AEGISUB_VERSION_STRING, __version__

LINEBREAK = "\r\n"

_FORMAT = {
    Group.DIALOGUE: "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    Group.STYLE: (
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
        "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding"
    ),
}

AEGISUB_GENERATED = "; Script generated by Aegisub "
_OURS = re.compile(r" with aegisub-render \S+$")


def header_lines(ass: AssFile, keep_brand: bool = False) -> list[str]:
    """The comment lines after [Script Info]. Aegisub writes its own two; here:

    * keep_brand: the input's header comments, unchanged (none if it had none);
    * otherwise, when the input says it was generated by Aegisub, that line (with its Aegisub
      version) gets " with aegisub-render <ver>" appended, replacing an earlier one; any other
      header is replaced by the standard one naming the Aegisub version followed here.
    """
    if keep_brand:
        return list(ass.header_comments)
    with_us = f" with aegisub-render {__version__}"
    first = ass.header_comments[0] if ass.header_comments else ""
    if first.startswith(AEGISUB_GENERATED):
        generated = _OURS.sub("", first) + with_us
    else:
        generated = f"{AEGISUB_GENERATED}{AEGISUB_VERSION_STRING}{with_us}"
    return [generated, "; https://aegisub.org/"]


class _Writer:
    def __init__(self, header: list[str]) -> None:
        self.out: list[str] = []
        self.group = Group.INFO
        self.line("[Script Info]")
        for comment in header:
            self.line(comment)

    def line(self, text: str) -> None:
        self.out.append(text + LINEBREAK)

    def write_entries(self, entries: list[AnyEntry]) -> None:
        for entry in entries:
            if entry.group != self.group:
                self.line("")
                self.line(GROUP_HEADERS[entry.group])
                fmt = _FORMAT.get(entry.group)
                if fmt is not None:
                    self.line(fmt)
                self.group = entry.group
            self.line(entry.entry_data())

    def write_properties(self, p: ProjectProperties, save_ui_state: bool) -> None:
        self.line("")
        self.line("[Aegisub Project Garbage]")

        def if_not_empty(key: str, value: str) -> None:
            if value:
                self.line(key + value)

        if_not_empty("Automation Scripts: ", p.automation_scripts)
        if_not_empty("Export Filters: ", p.export_filters)
        if_not_empty("Export Encoding: ", p.export_encoding)
        if_not_empty("Last Style Storage: ", p.style_storage)
        if_not_empty("Audio File: ", p.audio_file)
        if_not_empty("Video File: ", p.video_file)
        if_not_empty("Timecodes File: ", p.timecodes_file)
        if_not_empty("Keyframes File: ", p.keyframes_file)
        if p.ar_mode != 0:
            self.line(f"Video AR Mode: {p.ar_mode}")
        if p.ar_value != 0:
            self.line("Video AR Value: " + format_f(p.ar_value))
        if save_ui_state:
            if p.video_zoom != 0:
                self.line("Video Zoom Percent: " + format_f(p.video_zoom))
            if p.scroll_position != 0:
                self.line(f"Scroll Position: {p.scroll_position}")
            if p.active_row != 0:
                self.line(f"Active Line: {p.active_row}")
            if p.video_position != 0:
                self.line(f"Video Position: {p.video_position}")

    def write_extradata(self, ass: AssFile) -> None:
        if not ass.extradata:
            return
        self.group = Group.EXTRADATA
        self.line("")
        self.line("[Aegisub Extradata]")
        for e in ass.extradata:
            text = f"Data: {e.id},{inline_string_encode(e.key)},"
            encoded = inline_string_encode(e.value)
            raw_value = to_bytes(e.value)
            if 4 * len(raw_value) < 3 * len(to_bytes(encoded)):
                text += "u" + uuencode(raw_value, False)
            else:
                text += "e" + encoded
            self.line(text)

    def data(self) -> bytes:
        return b"\xef\xbb\xbf" + to_bytes("".join(self.out))


def serialize_ass(ass: AssFile, save_ui_state: bool = True, keep_brand: bool = False) -> bytes:
    """SubsController::Save: CleanExtradata, then AssSubtitleFormat::WriteFile."""
    ass.clean_extradata()
    w = _Writer(header_lines(ass, keep_brand))
    w.write_entries(list(ass.info))
    w.write_properties(ass.properties, save_ui_state)
    w.write_entries(list(ass.styles))
    w.write_entries(list(ass.attachments))
    w.write_entries(list(ass.events))
    w.write_extradata(ass)
    return w.data()


def serialize_export(ass: AssFile, save_ui_state: bool = True, keep_brand: bool = False) -> bytes:
    """AssExporter::Export: AssSubtitleFormat::ExportFile, which leaves out the Project Garbage and
    the Extradata. Unlike Aegisub, either section is kept, written as Save writes it, when the
    input had it: the result may replace the input, which must not lose them."""
    w = _Writer(header_lines(ass, keep_brand))
    w.write_entries(list(ass.info))
    if ass.had_project_garbage:
        w.write_properties(ass.properties, save_ui_state)
    w.write_entries(list(ass.styles))
    w.write_entries(list(ass.attachments))
    w.write_entries(list(ass.events))
    if ass.had_extradata:
        ass.clean_extradata()
        w.write_extradata(ass)
    return w.data()


def write_ass_file(data: bytes, path: Path) -> None:
    """Write atomically: the destination is only replaced once the whole file is ready."""
    tmp = path.with_name(path.name + ".aegisub-render.tmp")
    tmp.write_bytes(data)
    tmp.replace(path)
