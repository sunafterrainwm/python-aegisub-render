"""Build aegisub-render.exe, which runs `<repo>\\.venv\\Scripts\\python.exe <repo>\\aegisub-render.py ...`.

    uv run python scripts/build_exe.py [-o aegisub-render.exe] [--python PATH]

The .exe is what pip puts in front of console scripts: distlib's console launcher (t64.exe;
pip vendors distlib), then a "#!<python>" line, then a zip archive with a __main__.py. The
launcher reads the interpreter back from the end of its own file and runs `<python> <the .exe>
args...`, Python runs the archive's __main__.py, and that runs aegisub-render.py; exit codes and
Ctrl+C pass through. Both paths are absolute, so the .exe also works when copied elsewhere (into
a directory on PATH, say), but it has to be rebuilt when the repository or its .venv moves.
"""

import argparse
import io
import sys
import zipfile
from collections.abc import Sequence
from importlib.resources import files
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "aegisub-render.py"
DEFAULT_PYTHON = ROOT / ".venv" / "Scripts" / "python.exe"
DEFAULT_OUTPUT = ROOT / "aegisub-render.exe"

MAIN = """\
# Generated by scripts/build_exe.py: the same as `python aegisub-render.py ...`.
import runpy

runpy.run_path({script!r}, run_name="__main__")
"""


def launcher() -> bytes:
    """distlib's console launcher for x64 (the Cython modules are built for win_amd64 only)."""
    return (files("distlib") / "t64.exe").read_bytes()


def shebang(python: Path) -> bytes:
    """The interpreter line, quoted like distlib does when the path has spaces."""
    path = str(python)
    if " " in path:
        path = f'"{path}"'
    return b"#!" + path.encode("utf-8") + b"\n"


def build(output: Path, python: Path, script: Path = SCRIPT) -> None:
    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        # A fixed timestamp: the same paths give the same .exe.
        zf.writestr(zipfile.ZipInfo("__main__.py", (1980, 1, 1, 0, 0, 0)), MAIN.format(script=str(script)))
    output.write_bytes(launcher() + shebang(python) + archive.getvalue())


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build aegisub-render.exe (a launcher for aegisub-render.py).")
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT, help="default: %(default)s")
    parser.add_argument(
        "--python", type=Path, default=DEFAULT_PYTHON, help="interpreter the .exe runs (default: %(default)s)"
    )
    args = parser.parse_args(argv)
    # absolute(), not resolve(): a venv's python.exe must not be replaced by what it points to.
    python: Path = args.python.absolute()
    output: Path = args.output.absolute()
    if not python.is_file():
        print(f"build_exe: {python} does not exist (run `uv sync` first)", file=sys.stderr)
        return 1
    try:
        build(output, python)
    except OSError as e:
        print(f"build_exe: could not write {output}: {e}", file=sys.stderr)
        return 1
    print(f"{output}: runs {python} {SCRIPT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
